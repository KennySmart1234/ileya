



def get_even_and_odd(numbers):
    even_list = []
    odd_list = []
    even_and_odd = [even_list, odd_list]

    for number in numbers:
        if(number % 2 == 0):
    
            even_list.append(number)
        else:
            odd_list.append(number) 
                       
    return even_and_odd



